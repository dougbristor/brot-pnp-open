#!/usr/bin/env node
// codetree:cramer3_solve/v1 — conformance runner
//
//   node conform.mjs                 check this block's own v1.js
//   node conform.mjs <path-to.js>    check any module that exports cramer3
//
// WHY THIS EXISTS RATHER THAN A SHARED IMPLEMENTATION. `cramer3` lives in 28 files across
// five agents in JavaScript, and the same job is done in Python by
// `julia_bristor/bristor_inverse_julia.py` (np.linalg.solve against bristor_jacobian, the
// same Newton step) where the text cannot travel. Verified by reading that file, not assumed:
// a GLSL instance may well exist, but this block does not claim one it has not opened.
//
// A generated "proto" implementation would make every copy agree by construction — which
// removes exactly the independence that catches errors, and produces a reference no site
// actually runs (measured across this tree: no planted block exceeds 60% coverage at its own
// extraction source — fable/RESULT_codetree_faults_20260920.md).
//
// So the portable artefact is NOT the code. It is `vectors.json`: inputs, expected outputs
// computed by an independent method, and the failure cases named. Every implementation stays
// hand-written and idiomatic; the table is what says they are the same thing.
//
// THE EXPECTATIONS ARE NOT FROM THIS CODE. They come from Gaussian elimination with partial
// pivoting over exact rationals — a different algorithm from the block's cofactor expansion.
// Expectations generated by the implementation under test cannot fail, and a check that
// cannot fail is the failure this project keeps filing (F-06, F-12, F-15).
//
// CAVEAT CASES ARE ASSERTIONS ABOUT DOCUMENTED WRONGNESS. The block's known caveat — the
// 1e-14 tolerance is absolute, never scaled by the magnitude of A — is encoded as two cases
// that must keep misbehaving in the documented way. If one stops, the block's prose is stale:
// that is reported as STALE CAVEAT, not as a pass and not as a code failure.
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const here = path.dirname(fileURLToPath(import.meta.url));
const doc = JSON.parse(fs.readFileSync(path.join(here, 'vectors.json'), 'utf8'));
const target = process.argv[2] ? path.resolve(process.argv[2]) : path.join(here, 'v1.js');
const { cramer3 } = await import(target);

const rel = (got, want) => Math.max(...got.map((v, i) =>
  Math.abs(v - want[i]) / Math.max(1e-300, Math.abs(want[i]))));

let fail = 0, stale = 0;
console.log(`cramer3_solve — ${doc.cases.length} vectors against ${path.relative(process.cwd(), target)}`);
console.log(`expectations from: ${doc.expectations_from.split('—')[0].trim()}\n`);

for (const c of doc.cases) {
  const got = cramer3(...c.A.flat(), ...c.b);
  let ok, note;
  if (c.kind === 'null') {
    ok = got === null; note = got === null ? 'null as required' : `returned ${JSON.stringify(got)}`;
  } else if (c.kind === 'solve') {
    if (got === null) { ok = false; note = 'returned null for a solvable system'; }
    else { const e = rel(got, c.expect); ok = e <= doc.tol; note = `rel err ${e.toExponential(2)}`; }
  } else {                                    // caveat — must still misbehave as documented
    if (c.assert_ === 'null') {
      ok = got === null;
      note = ok ? `still rejects a system solvable to ${JSON.stringify(c.exact)}`
                : `NO LONGER rejects it — returned ${JSON.stringify(got)}`;
    } else {
      const e = got === null ? null : rel(got, c.exact);
      ok = got !== null && e > 1e-6;
      note = got === null ? 'NO LONGER accepts it — returned null'
                          : `accepted, rel err ${e.toExponential(2)}${ok ? '' : ' — now accurate'}`;
    }
    if (!ok) stale++;
  }
  if (!ok && c.kind !== 'caveat') fail++;
  const tag = ok ? (c.kind === 'caveat' ? 'documented' : 'ok') : (c.kind === 'caveat' ? 'STALE' : 'FAIL');
  console.log(`  ${tag.padEnd(10)} ${c.name.padEnd(30)} det=${String(c.det).padEnd(10)} ${note}`);
}

console.log();
if (fail) console.log(`${fail} FAILURE(S) — this implementation does not match the contract.`);
if (stale) console.log(`${stale} STALE CAVEAT(S) — the code changed and block.md now describes ` +
                       `behaviour it no longer has. Fix the prose, not the code.`);
if (!fail && !stale) console.log('conforms — including both documented caveats, which still bite.');
process.exit(fail ? 1 : 0);
